from TestSim import *
def main():
    s = TestSim()
    s.loadTopo("long_line.topo")
    s.loadNoise("no_noise.txt")
    s.bootAll()
    s.addChannel(s.COMMAND_CHANNEL)
    s.addChannel(s.NEIGHBOR_CHANNEL)
    s.addChannel(s.FLOODING_CHANNEL)
    s.runForSeconds(8)
    s.neighborDMP(5)
    s.runForSeconds(1)
    s.ping(2, 18, "too far")
    s.runForSeconds(15)
    s.neighborDMP(3)
    s.runForSeconds(1)
    s.moteOff(4)
    s.runForSeconds(7)
    s.neighborDMP(5)
    s.runForSeconds(1)
if __name__ == '__main__': main()
